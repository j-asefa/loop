import type { CatalogEntry, CatalogInput } from "../../shared/mcp-catalog.js";

// Curated entries are reviewed against publisher documentation. Community entries
// come from the official MCP Registry and are pinned to verified npm versions.
// Only these checked-in targets can be installed through the catalog API.
// Package versions are pinned; changing a catalog target requires a source change.
export const reviewedAt = "2026-09-26";
export type CatalogDefinition = CatalogEntry & {
  server:
    | { url: string }
    | { package: string; args: string[]; env: Record<string, string> };
};
const key = (key: string, label: string, secret = true): CatalogInput => ({
  key,
  label,
  secret,
});
function http(
  id: string,
  name: string,
  publisher: string,
  category: string,
  description: string,
  url: string,
  source: string,
  auth: CatalogEntry["auth"] = "oauth",
  note?: string,
): CatalogDefinition {
  return {
    id,
    name,
    publisher,
    category,
    description,
    source,
    auth,
    note,
    transport: "http",
    serverUrl: url,
    server: { url },
    inputs:
      auth === "bearer" || auth === "query"
        ? [key("token", "Access token / API key")]
        : auth === "oauth-app"
          ? [
              key("clientId", "OAuth client ID", false),
              key("clientSecret", "OAuth client secret"),
            ]
          : [],
  };
}
function npm(
  id: string,
  name: string,
  publisher: string,
  category: string,
  description: string,
  pkg: string,
  source: string,
  inputs: CatalogInput[] = [],
  args: string[] = [],
  env: Record<string, string> = {},
  note?: string,
): CatalogDefinition {
  return {
    id,
    name,
    publisher,
    category,
    description,
    source,
    inputs,
    note,
    auth: inputs.length ? "env" : "none",
    transport: "stdio",
    server: { package: pkg, args, env },
  };
}
