import { ConversationId, RunId, requestId } from "./contract-ids.js";
import { z } from "zod";
import * as mobile from "./mobile-contract-schemas.js";
import * as library from "./library-contract-schemas.js";
import { ProviderSchema as Provider } from "./provider-schema.js";
import {
  Text,
  MaybeText,
  Empty,
  Id,
  Ok,
  endpoint,
  base,
} from "./route-contract.js";
import {
  PublicFolder,
  PublicMessage,
  PublicArtifact,
  PublicRun,
} from "./workspace-contract-schemas.js";

export const libraryRoutes = {
  messageSearch: endpoint({
    ...base,
    operation: "messageSearch",
    access: { admits: ["read"] },
    method: "GET",
    path: "/messages",
    query: z.object({ q: Text.max(500).default("") }),
    response: z.array(PublicMessage),
  }),
  messageDetail: endpoint({
    ...base,
    operation: "messageDetail",
    access: { admits: ["read"] },
    method: "GET",
    path: "/messages/:id",
    params: Id,
    response: PublicMessage,
  }),
  resultUpdate: endpoint({
    ...base,
    operation: "resultUpdate",
    method: "PATCH",
    path: "/results/:id",
    params: Id,
    body: z.object({ hidden: z.boolean() }),
    response: Ok,
  }),
  artifactFile: endpoint({
    ...base,
    operation: "artifactFile",
    access: { admits: ["read"] },
    method: "GET",
    path: "/artifacts/:id/file",
    params: Id,
    query: z.object({ preview: z.unknown().optional() }),
    kind: "stream",
    response: z.custom<Blob>(),
  }),
  artifactDownload: endpoint({
    ...base,
    operation: "artifactDownload",
    access: { admits: ["read"] },
    method: "GET",
    path: "/artifacts/:id/download",
    params: Id,
    kind: "stream",
    response: z.custom<Blob>(),
    status: 303,
  }),
  snippetList: endpoint({
    ...base,
    operation: "snippetList",
    method: "GET",
    path: "/snippets",
    response: mobile.PublicSnippets,
  }),
  uploadCreate: endpoint({
    ...base,
    operation: "uploadCreate",
    method: "POST",
    path: "/uploads",
    multipart: true,
    body: library.UploadOptions,
    response: mobile.PublicUploadDescriptor,
    status: 201,
  }),
  folderList: endpoint({
    ...base,
    operation: "folderList",
    method: "GET",
    path: "/folders",
    response: z.array(PublicFolder),
  }),
  folderCreate: endpoint({
    ...base,
    operation: "folderCreate",
    method: "POST",
    path: "/folders",
    body: library.FolderCreateInput,
    response: PublicFolder,
    status: 201,
  }),
  folderUpdate: endpoint({
    ...base,
    operation: "folderUpdate",
    method: "PATCH",
    path: "/folders/:id",
    params: Id,
    body: library.FolderUpdateInput,
    response: Ok,
  }),
  artifactList: endpoint({
    ...base,
    operation: "artifactList",
    access: { admits: ["read"] },
    method: "GET",
    path: "/artifacts",
    query: library.ArtifactListQuery,
    response: z.object({
      items: z.array(
        PublicArtifact.extend({
          cursor: z.number(),
          name: MaybeText,
          provider: Provider.nullable(),
        }),
      ),
      next: z.number().nullable(),
    }),
  }),
  artifactDetail: endpoint({
    ...base,
    operation: "artifactDetail",
    access: { admits: ["read"] },
    method: "GET",
    path: "/artifacts/:id",
    params: Id,
    response: PublicArtifact,
  }),
  artifactCreate: endpoint({
    ...base,
    operation: "artifactCreate",
    method: "POST",
    path: "/artifacts",
    body: library.ArtifactCreateInput,
    response: z.object({ id: Text }),
    status: 201,
  }),
  artifactUpdate: endpoint({
    ...base,
    operation: "artifactUpdate",
    method: "PATCH",
    path: "/artifacts/:id",
    params: Id,
    body: library.ArtifactUpdateInput,
    response: PublicArtifact,
  }),
  artifactMove: endpoint({
    ...base,
    operation: "artifactMove",
    method: "POST",
    path: "/artifacts/:id/move",
    params: Id,
    body: library.ArtifactMoveInput,
    response: z.object({ operation: Text, folderId: MaybeText, message: Text }),
  }),
  runCheckout: endpoint({
    ...base,
    operation: "runCheckout",
    method: "GET",
    path: "/runs/:id/checkout",
    params: z.object({ id: requestId(RunId) }),
    response: library.PublicCheckout,
  }),
  runVerifications: endpoint({
    ...base,
    operation: "runVerifications",
    method: "GET",
    path: "/runs/:id/verifications",
    params: z.object({ id: requestId(RunId) }),
    response: z.array(library.PublicVerification),
  }),
  runFiles: endpoint({
    ...base,
    operation: "runFiles",
    method: "GET",
    path: "/runs/:id/files",
    params: z.object({ id: requestId(RunId) }),
    response: z.array(z.object({ id: Text, title: Text, metadata: Text })),
  }),
  operationUndo: endpoint({
    ...base,
    operation: "operationUndo",
    method: "POST",
    path: "/operations/:id/undo",
    params: Id,
    body: z.unknown(),
    response: Ok.extend({ folderId: MaybeText }),
  }),
  objectFile: endpoint({
    ...base,
    operation: "objectFile",
    access: { admits: ["read"] },
    method: "GET",
    path: "/objects/:id",
    params: Id,
    query: z.object({ preview: z.unknown().optional() }),
    kind: "stream",
    response: z.custom<Blob>(),
  }),
  search: endpoint({
    ...base,
    operation: "search",
    method: "GET",
    path: "/search",
    query: library.SearchQuery,
    response: library.PublicSearch,
  }),
  searchStatus: endpoint({
    ...base,
    operation: "searchStatus",
    method: "GET",
    path: "/search/status",
    response: library.PublicSearchStatus,
  }),
  preferences: endpoint({
    ...base,
    operation: "preferences",
    method: "GET",
    path: "/preferences",
    response: library.PublicPreferences,
  }),
  preferencesUpdate: endpoint({
    ...base,
    operation: "preferencesUpdate",
    method: "POST",
    path: "/preferences",
    body: library.PreferencesInput,
    response: Ok,
  }),
  importPreview: endpoint({
    ...base,
    operation: "importPreview",
    method: "POST",
    path: "/imports/preview",
    multipart: true,
    body: Empty,
    response: library.PublicImportPreview,
  }),
  importList: endpoint({
    ...base,
    operation: "importList",
    method: "GET",
    path: "/imports",
    response: z.array(library.PublicImport),
  }),
  importStart: endpoint({
    ...base,
    operation: "importStart",
    method: "POST",
    path: "/imports/:id/start",
    params: Id,
    body: z.unknown(),
    response: z.union([
      PublicRun,
      z.object({ status: z.literal("completed") }),
    ]),
  }),
  importCancel: endpoint({
    ...base,
    operation: "importCancel",
    method: "POST",
    path: "/imports/:id/cancel",
    params: Id,
    body: z.unknown(),
    response: Ok,
  }),
  conversationContinueStart: endpoint({
    ...base,
    operation: "conversationContinueStart",
    method: "POST",
    path: "/conversations/:id/continue/start",
    params: z.object({ id: requestId(ConversationId) }),
    body: library.ContinueInput,
    response: z.object({
      id: Text,
      agentId: Text,
      runId: Text,
      unavailable: z.literal(true).optional(),
    }),
  }),
} as const;
