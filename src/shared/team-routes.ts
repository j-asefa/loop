import { z } from "zod";
import * as teams from "./team-contract-schemas.js";
import { PublicMailThreads, PublicMailResume } from "./agent-mail.js";
import { Text, Id, Ok, endpoint, base } from "./route-contract.js";
import {
  PublicAgent,
  PublicTeam,
  PublicRun,
} from "./workspace-contract-schemas.js";

export const teamRoutes = {
  teamList: endpoint({
    ...base,
    operation: "teamList",
    method: "GET",
    path: "/teams",
    response: z.array(PublicTeam),
  }),
  teamPresets: endpoint({
    ...base,
    operation: "teamPresets",
    method: "GET",
    path: "/team-presets",
    response: z.array(teams.PublicTeamPreset),
  }),
  teamCreate: endpoint({
    ...base,
    operation: "teamCreate",
    method: "POST",
    path: "/teams",
    body: teams.TeamCreateInput,
    response: PublicTeam,
    status: 201,
  }),
  teamFromPreset: endpoint({
    ...base,
    operation: "teamFromPreset",
    method: "POST",
    path: "/teams/from-preset",
    body: teams.TeamPresetInput,
    response: PublicTeam,
    status: 201,
  }),
  teamMemberAdd: endpoint({
    ...base,
    operation: "teamMemberAdd",
    method: "POST",
    path: "/teams/:id/members",
    params: Id,
    body: z.object({ agentId: Text.min(1) }),
    response: PublicTeam,
  }),
  teamFeedVisibility: endpoint({
    ...base,
    operation: "teamFeedVisibility",
    method: "PATCH",
    path: "/teams/:id/feed-visibility",
    params: Id,
    body: z.object({ hideResultsFromFeed: z.boolean() }),
    response: PublicTeam,
  }),
  teamDelete: endpoint({
    ...base,
    operation: "teamDelete",
    method: "DELETE",
    path: "/teams/:id",
    params: Id,
    body: z.unknown(),
    response: Ok,
  }),
  teamReview: endpoint({
    ...base,
    operation: "teamReview",
    method: "POST",
    path: "/teams/:id/reviews",
    params: Id,
    body: teams.ReviewInput,
    response: teams.PublicReview,
    status: 201,
  }),
  reviewStatus: endpoint({
    ...base,
    operation: "reviewStatus",
    method: "GET",
    path: "/reviews/conversation/:id",
    params: Id,
    query: z.object({ freshness: Text.optional() }),
    response: teams.PublicReview.nullable(),
  }),
  teamMessages: endpoint({
    ...base,
    operation: "teamMessages",
    method: "GET",
    path: "/teams/:id/messages",
    params: Id,
    response: PublicMailThreads,
  }),
  teamThreadResume: endpoint({
    ...base,
    operation: "teamThreadResume",
    method: "POST",
    path: "/teams/:id/threads/:threadId/resume",
    params: Id.extend({ threadId: Text }),
    body: z.unknown(),
    response: PublicMailResume,
  }),
  agentMail: endpoint({
    ...base,
    operation: "agentMail",
    method: "GET",
    path: "/agents/:id/mail",
    params: Id,
    response: PublicMailThreads,
  }),
  agentMailResume: endpoint({
    ...base,
    operation: "agentMailResume",
    method: "POST",
    path: "/agents/:id/mail/:threadId/resume",
    params: Id.extend({ threadId: Text }),
    body: z.unknown(),
    response: PublicMailResume,
  }),
  definitionList: endpoint({
    ...base,
    operation: "definitionList",
    method: "GET",
    path: "/agent-definitions",
    response: z.array(teams.PublicDefinitionSummary),
  }),
  definitionRead: endpoint({
    ...base,
    operation: "definitionRead",
    method: "GET",
    path: "/agent-definitions/:id",
    params: Id,
    response: teams.PublicDefinition,
  }),
  definitionSave: endpoint({
    ...base,
    operation: "definitionSave",
    method: "PUT",
    path: "/agent-definitions/:id",
    params: z.object({ id: Text.uuid() }),
    body: teams.DefinitionSaveInput,
    response: teams.PublicDefinition,
  }),
  definitionDelete: endpoint({
    ...base,
    operation: "definitionDelete",
    method: "DELETE",
    path: "/agent-definitions/:id",
    params: Id,
    body: z.strictObject({ version: teams.DefinitionVersion }),
    response: Ok,
  }),
  definitionCreate: endpoint({
    ...base,
    operation: "definitionCreate",
    method: "POST",
    path: "/agent-definitions/:id/create",
    params: Id,
    body: teams.DefinitionCreateInput,
    response: z.union([
      z.object({ agent: PublicAgent, team: PublicTeam.optional() }),
      z.object({ team: PublicTeam }),
    ]),
    status: 201,
  }),
  sharePreview: endpoint({
    ...base,
    operation: "sharePreview",
    method: "POST",
    path: "/share/preview",
    body: teams.ShareInput,
    response: teams.PublicSharePreview,
  }),
  shareSend: endpoint({
    ...base,
    operation: "shareSend",
    method: "POST",
    path: "/share/send",
    body: teams.ShareSendInput,
    response: PublicRun,
  }),
  routingPreview: endpoint({
    ...base,
    operation: "routingPreview",
    method: "POST",
    path: "/routing/preview",
    body: teams.RoutingInput,
    response: z.object({ agent: PublicAgent.nullable(), reason: Text }),
  }),
} as const;
