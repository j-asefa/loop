import { ConversationId, requestId, PrWatchId } from "./contract-ids.js";
import { z } from "zod";
import * as github from "./github-contract-schemas.js";
import { Text, Ok, endpoint, base } from "./route-contract.js";

export const githubRoutes = {
  prWatchList: endpoint({
    ...base,
    operation: "prWatchList",
    method: "GET",
    path: "/pr-watches",
    query: z.object({
      conversation: requestId(ConversationId).max(150).optional(),
    }),
    response: z.object({ watches: z.array(github.PublicPrWatch) }),
  }),
  prWatchCreate: endpoint({
    ...base,
    operation: "prWatchCreate",
    method: "POST",
    path: "/pr-watches",
    body: github.PrWatchInput,
    response: github.PublicCreatedPrWatch,
    status: 201,
  }),
  prWatchResume: endpoint({
    ...base,
    operation: "prWatchResume",
    method: "POST",
    path: "/pr-watches/:id/resume",
    params: z.object({ id: requestId(PrWatchId) }),
    body: z.unknown(),
    response: Ok,
  }),
  prWatchDelete: endpoint({
    ...base,
    operation: "prWatchDelete",
    method: "DELETE",
    path: "/pr-watches/:id",
    params: z.object({ id: requestId(PrWatchId) }),
    body: z.unknown(),
    response: Ok,
  }),
  githubPullList: endpoint({
    ...base,
    operation: "githubPullList",
    method: "GET",
    path: "/github/pulls",
    query: github.PullQuery,
    response: github.PublicPullInbox,
  }),
  githubPullDetail: endpoint({
    ...base,
    operation: "githubPullDetail",
    method: "GET",
    path: "/github/pulls/:owner/:repo/:number",
    params: github.PullParams,
    response: github.PublicPullDetail,
  }),
  githubPullFiles: endpoint({
    ...base,
    operation: "githubPullFiles",
    method: "GET",
    path: "/github/pulls/:owner/:repo/:number/files",
    params: github.PullParams,
    query: z.object({ head: github.CommitSha }),
    response: github.PublicPullFiles,
  }),
  githubPullCommitFiles: endpoint({
    ...base,
    operation: "githubPullCommitFiles",
    method: "GET",
    path: "/github/pulls/:owner/:repo/:number/commits/:sha/files",
    params: github.PullParams.extend({ sha: github.CommitSha }),
    response: github.PublicCommitFiles,
  }),
  githubPullFile: endpoint({
    ...base,
    operation: "githubPullFile",
    method: "GET",
    path: "/github/pulls/:owner/:repo/:number/file",
    params: github.PullParams,
    query: github.PullFileQuery,
    kind: "stream",
    response: z.custom<Blob>(),
  }),
  githubPullReview: endpoint({
    ...base,
    operation: "githubPullReview",
    method: "POST",
    path: "/github/pulls/:owner/:repo/:number/reviews",
    params: github.PullParams,
    body: github.PullReviewInput,
    response: Ok.extend({ url: Text.optional() }),
    status: 201,
  }),
  githubPullComment: endpoint({
    ...base,
    operation: "githubPullComment",
    method: "POST",
    path: "/github/pulls/:owner/:repo/:number/comments",
    params: github.PullParams,
    body: github.PullCommentInput,
    response: Ok.extend({ url: Text.optional() }),
    status: 201,
  }),
  githubPullMerge: endpoint({
    ...base,
    operation: "githubPullMerge",
    method: "POST",
    path: "/github/pulls/:owner/:repo/:number/merge",
    params: github.PullParams,
    body: github.PullMergeInput,
    response: z.object({ merged: z.boolean(), sha: Text.optional() }),
  }),
} as const;
