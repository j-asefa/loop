import {
  AgentId,
  ConnectionId,
  requestId,
  ConversationId,
  RunId,
} from "./contract-ids.js";
import { z } from "zod";
import {
  AgentCreateInput,
  AgentUpdateInput,
  ConnectionCreateInput,
  ConnectionReconnectInput,
  PublicModels,
  PublicConnectionRefresh,
  PublicHarnessCatalog,
  PublicPiConfiguration,
  PublicPiMutation,
  PublicPiInspection,
  PiTrustInput,
  PiFiltersInput,
  PiPreviewInput,
  PiInspectInput,
  PiRollbackInput,
  PiActionInput,
  PublicAgentMessages,
  PublicAgentTraces,
} from "./agent-contract-schemas.js";
import { Text, Ok, endpoint, base } from "./route-contract.js";
import {
  PublicAgent,
  PublicConnection,
  PublicRun,
  PublicConversation,
} from "./workspace-contract-schemas.js";

export const agentRoutes = {
  connectionCreate: endpoint({
    ...base,
    operation: "connectionCreate",
    method: "POST",
    path: "/connections",
    body: ConnectionCreateInput,
    response: PublicConnection.pick({ id: true }).extend(PublicModels.shape),
  }),
  connectionRefresh: endpoint({
    ...base,
    operation: "connectionRefresh",
    method: "POST",
    path: "/connections/:id/refresh",
    params: z.object({ id: requestId(ConnectionId) }),
    body: z.unknown(),
    response: PublicConnectionRefresh,
  }),
  connectionModels: endpoint({
    ...base,
    operation: "connectionModels",
    method: "GET",
    path: "/connections/:id/models",
    params: z.object({ id: requestId(ConnectionId) }),
    response: PublicModels,
  }),
  connectionReconnect: endpoint({
    ...base,
    operation: "connectionReconnect",
    method: "POST",
    path: "/connections/:id/reconnect",
    params: z.object({ id: requestId(ConnectionId) }),
    body: ConnectionReconnectInput,
    response: Ok,
  }),
  connectionDisconnect: endpoint({
    ...base,
    operation: "connectionDisconnect",
    method: "DELETE",
    path: "/connections/:id",
    params: z.object({ id: requestId(ConnectionId) }),
    body: z.unknown(),
    response: Ok,
  }),
  agentSuggestName: endpoint({
    ...base,
    operation: "agentSuggestName",
    method: "GET",
    path: "/agents/suggest-name",
    response: z.object({ name: Text }),
  }),
  agentCreate: endpoint({
    ...base,
    operation: "agentCreate",
    method: "POST",
    path: "/agents",
    body: AgentCreateInput,
    response: PublicAgent.extend({
      initialRun: z
        .object({ id: RunId, conversation_id: ConversationId.nullable() })
        .optional(),
    }),
    status: 201,
  }),
  agentUpdate: endpoint({
    ...base,
    operation: "agentUpdate",
    method: "PATCH",
    path: "/agents/:id",
    params: z.object({ id: requestId(AgentId) }),
    body: AgentUpdateInput,
    response: PublicAgent,
  }),
  agentDetail: endpoint({
    ...base,
    operation: "agentDetail",
    access: { admits: ["read"] },
    method: "GET",
    path: "/agents/:id",
    params: z.object({ id: requestId(AgentId) }),
    response: z.object({
      agent: PublicAgent,
      runs: z.array(PublicRun),
      conversations: z.array(PublicConversation),
    }),
  }),
  agentHarness: endpoint({
    ...base,
    operation: "agentHarness",
    method: "GET",
    path: "/agents/:id/harness",
    params: z.object({ id: requestId(AgentId) }),
    query: z.object({
      conversation: requestId(ConversationId).uuid().optional(),
    }),
    response: PublicHarnessCatalog,
  }),
  agentMessages: endpoint({
    ...base,
    operation: "agentMessages",
    access: { admits: ["read"] },
    method: "GET",
    path: "/agents/:id/messages",
    params: z.object({ id: requestId(AgentId) }),
    query: z.object({ before: Text.min(1).max(512).optional() }),
    response: PublicAgentMessages,
  }),
  agentTraces: endpoint({
    ...base,
    operation: "agentTraces",
    access: { admits: ["read"] },
    method: "GET",
    path: "/agents/:id/traces",
    params: z.object({ id: requestId(AgentId) }),
    query: z.object({
      before: z.coerce
        .number<string>()
        .int()
        .positive()
        .max(Number.MAX_SAFE_INTEGER)
        .optional(),
      run: requestId(RunId).min(1).max(100).optional(),
      q: Text.max(500).optional(),
    }),
    response: PublicAgentTraces,
  }),
  agentTracesExport: endpoint({
    ...base,
    operation: "agentTracesExport",
    access: { admits: ["read"] },
    method: "GET",
    path: "/agents/:id/traces/export",
    params: z.object({ id: requestId(AgentId) }),
    query: z.object({ run: requestId(RunId).min(1).max(100) }),
    kind: "stream",
    contentType: "application/json",
    response: z.custom<Blob>(),
  }),
  agentPiPackages: endpoint({
    ...base,
    operation: "agentPiPackages",
    method: "GET",
    path: "/agents/:id/pi-packages",
    params: z.object({ id: requestId(AgentId) }),
    response: PublicPiConfiguration,
  }),
  agentPiTrust: endpoint({
    ...base,
    operation: "agentPiTrust",
    method: "POST",
    path: "/agents/:id/pi-trust",
    params: z.object({ id: requestId(AgentId) }),
    body: PiTrustInput,
    response: PublicPiConfiguration,
  }),
  agentPiFilters: endpoint({
    ...base,
    operation: "agentPiFilters",
    method: "POST",
    path: "/agents/:id/pi-package-filters",
    params: z.object({ id: requestId(AgentId) }),
    body: PiFiltersInput,
    response: PublicPiMutation,
  }),
  agentPiPreview: endpoint({
    ...base,
    operation: "agentPiPreview",
    method: "POST",
    path: "/agents/:id/pi-prompt-preview",
    params: z.object({ id: requestId(AgentId) }),
    body: PiPreviewInput,
    response: z.object({ token: Text, expanded: Text }),
  }),
  agentPiInspect: endpoint({
    ...base,
    operation: "agentPiInspect",
    method: "POST",
    path: "/agents/:id/pi-package-inspect",
    params: z.object({ id: requestId(AgentId) }),
    body: PiInspectInput,
    response: PublicPiInspection,
  }),
  agentPiRollback: endpoint({
    ...base,
    operation: "agentPiRollback",
    method: "POST",
    path: "/agents/:id/pi-package-rollback",
    params: z.object({ id: requestId(AgentId) }),
    body: PiRollbackInput,
    response: PublicPiMutation,
  }),
  agentPiAction: endpoint({
    ...base,
    operation: "agentPiAction",
    method: "POST",
    path: "/agents/:id/pi-packages",
    params: z.object({ id: requestId(AgentId) }),
    body: PiActionInput,
    response: PublicPiMutation,
  }),
} as const;
