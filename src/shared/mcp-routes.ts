import {
  AgentId,
  ArtifactId,
  requestId,
  McpCandidateId,
  McpCatalogEntryId,
  McpConnectionId,
} from "./contract-ids.js";
import { z } from "zod";
import * as mcp from "./mcp-contract-schemas.js";
import { Text, endpoint, base } from "./route-contract.js";
import { PublicRun, CardErrorSchema } from "./workspace-contract-schemas.js";

export const mcpRoutes = {
  mcpPreferences: endpoint({
    ...base,
    operation: "mcpPreferences",
    method: "GET",
    path: "/mcp/preferences",
    response: mcp.PublicMcpPreferences,
  }),
  mcpPreferencesUpdate: endpoint({
    ...base,
    operation: "mcpPreferencesUpdate",
    method: "PUT",
    path: "/mcp/preferences",
    body: mcp.McpPreferencesInput,
    response: mcp.PublicMcpPreferences.extend({ resumed: z.number() }),
  }),
  mcpCatalog: endpoint({
    ...base,
    operation: "mcpCatalog",
    method: "GET",
    path: "/mcp/catalog",
    response: mcp.PublicMcpCatalog,
  }),
  mcpNativeCandidates: endpoint({
    ...base,
    operation: "mcpNativeCandidates",
    method: "GET",
    path: "/mcp/native-candidates",
    response: mcp.PublicMcpCandidates,
  }),
  mcpNativeImport: endpoint({
    ...base,
    operation: "mcpNativeImport",
    method: "POST",
    path: "/mcp/native-candidates/:id/import",
    params: z.object({ id: requestId(McpCandidateId) }),
    body: z.unknown(),
    response: mcp.PublicMcpInstall,
    status: 201,
  }),
  mcpCatalogInstall: endpoint({
    ...base,
    operation: "mcpCatalogInstall",
    method: "POST",
    path: "/mcp/catalog/:id/install",
    params: z.object({ id: requestId(McpCatalogEntryId) }),
    body: mcp.McpCatalogInput,
    response: mcp.PublicMcpCatalogInstall,
  }),
  mcpInstall: endpoint({
    ...base,
    operation: "mcpInstall",
    method: "POST",
    path: "/mcp/install",
    body: mcp.McpInstallInput,
    response: mcp.PublicMcpInstall,
    status: 201,
  }),
  mcpList: endpoint({
    ...base,
    operation: "mcpList",
    method: "GET",
    path: "/mcp",
    response: z.array(mcp.PublicMcpConnection),
  }),
  mcpCreate: endpoint({
    ...base,
    operation: "mcpCreate",
    method: "POST",
    path: "/mcp",
    body: mcp.McpCreateInput,
    response: mcp.PublicMcpConnection,
    status: 201,
  }),
  mcpTest: endpoint({
    ...base,
    operation: "mcpTest",
    method: "POST",
    path: "/mcp/:id/test",
    params: z.object({ id: requestId(McpConnectionId) }),
    body: z.unknown(),
    response: mcp.PublicMcpTest,
  }),
  mcpUpdate: endpoint({
    ...base,
    operation: "mcpUpdate",
    method: "PATCH",
    path: "/mcp/:id",
    params: z.object({ id: requestId(McpConnectionId) }),
    body: mcp.McpUpdateInput,
    response: mcp.PublicMcpConnection,
  }),
  mcpOauthCallback: endpoint({
    ...base,
    operation: "mcpOauthCallback",
    method: "GET",
    path: "/mcp/oauth/callback",
    query: z.object({
      state: z.unknown().optional(),
      code: z.unknown().optional(),
    }),
    kind: "stream",
    response: z.custom<Blob>(),
    status: 302,
  }),
  agentTools: endpoint({
    ...base,
    operation: "agentTools",
    method: "GET",
    path: "/agents/:id/tools",
    params: z.object({ id: requestId(AgentId) }),
    response: z.array(z.object({ connection_id: McpConnectionId, tool: Text })),
  }),
  agentToolsUpdate: endpoint({
    ...base,
    operation: "agentToolsUpdate",
    method: "PUT",
    path: "/agents/:id/tools",
    params: z.object({ id: requestId(AgentId) }),
    body: z.unknown(),
    response: CardErrorSchema,
    status: 410,
  }),
  artifactToolCall: endpoint({
    ...base,
    operation: "artifactToolCall",
    method: "POST",
    path: "/artifacts/:id/tool-call",
    params: z.object({ id: requestId(ArtifactId) }),
    body: mcp.McpToolCallInput,
    response: PublicRun,
  }),
  artifactRefresh: endpoint({
    ...base,
    operation: "artifactRefresh",
    method: "POST",
    path: "/artifacts/:id/refresh",
    params: z.object({ id: requestId(ArtifactId) }),
    body: mcp.McpToolCallInput.pick({ idempotencyKey: true }),
    response: PublicRun,
  }),
  artifactApp: endpoint({
    ...base,
    operation: "artifactApp",
    method: "GET",
    path: "/artifacts/:id/app",
    params: z.object({ id: requestId(ArtifactId) }),
    kind: "stream",
    contentType: "text/html",
    response: z.custom<Blob>(),
  }),
} as const;
